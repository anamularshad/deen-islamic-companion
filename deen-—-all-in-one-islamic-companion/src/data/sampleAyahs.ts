// In-memory cache for loaded surahs
const surahCache: Record<number, Ayah[]> = { ...BUILT_IN_SURAHS };

export async function getSurahVerses(surahNumber: number): Promise<Ayah[]> {
  if (surahCache[surahNumber]) {
    return surahCache[surahNumber];
  }

  try {
    // Verified standard AlQuran Cloud API (quran-uthmani, en.sahih, bn.bengali)
    const response = await fetch(
      `https://api.alquran.cloud/v1/surah/${surahNumber}/editions/quran-uthmani,en.sahih,bn.bengali`
    );

    if (!response.ok) {
      throw new Error(`Failed to load Surah ${surahNumber}: ${response.statusText}`);
    }

    const json = await response.json();
    if (json.code === 200 && Array.isArray(json.data) && json.data.length >= 2) {
      const arabicAyahs = json.data[0].ayahs;
      const englishAyahs = json.data[1].ayahs;
      const bengaliAyahs = json.data[2]?.ayahs || [];

      const parsed: Ayah[] = arabicAyahs.map((ar: any, idx: number) => {
        const en = englishAyahs[idx] || {};
        const bn = bengaliAyahs[idx] || {};
        const globalNumber = ar.number;

        return {
          numberInSurah: ar.numberInSurah,
          surahNumber: surahNumber,
          arabicText: ar.text,
          translationEn: en.text || '',
          translationBn: bn.text || '',
          audioUrl: `https://cdn.islamic.network/quran/audio/128/ar.alafasy/${globalNumber}.mp3`,
        };
      });

      surahCache[surahNumber] = parsed;
      return parsed;
    }
  } catch (err) {
    console.warn(`Could not load Surah ${surahNumber} from remote API, falling back to cached/default`, err);
  }

  // Graceful fallback
  return BUILT_IN_SURAHS[surahNumber] || [];
}
